print(f"Columns: {df.shape[1]:,}")

core_cols = ["ucid", "date_filed", "Activity", "event_judge"]
display(df[core_cols].head(10))

print("\nColumn names:")
print(df.columns.tolist())

print("\nDataFrame info:")
df.info()

"""## Basic dataset counts

We summarize the scope of the event log by counting events, cases, activity types, and the date range covered by the data.
"""

df["date_filed"] = pd.to_datetime(df["date_filed"], errors="coerce")

print(f"Events: {len(df):,}")
print(f"Cases: {df['ucid'].nunique():,}")
print(f"Activity types: {df['Activity'].nunique():,}")
print(f"Date range: {df['date_filed'].min().date()} to {df['date_filed'].max().date()}")

"""## Variable groups

The event log contains 97 content variables, plus one technical index column (`Unnamed: 0`) that appears when the CSV is loaded.

Following the structure described in the manuscript, the variables are organized into five groups:

1. Technical index column: a non-substantive index column created during file export.
2. Core event-log fields: the case identifier, event date, standardized activity label, and event judge.
3. Activity attributes: `attribute_*` variables that provide additional information about the procedural role or subtype of an event.
4. Case attributes: static case-level variables repeated across all events belonging to the same case, including case descriptors, judge identifiers, party characteristics, counsel counts, and related-case indicators.
5. Other columns: columns not captured by the rules above, if any.

The complete list of variables and definitions is provided in Appendix D of the manuscript. The complete list of Activities and Activity attributes is provided in Appendix C.
"""

technical_cols = ["Unnamed: 0"] if "Unnamed: 0" in df.columns else []

core_cols = [
    "ucid",
    "date_filed",
    "Activity",
    "event_judge"
]

activity_attribute_cols = [
    col for col in df.columns
    if col.startswith("attribute_")
]

case_attribute_cols = [
    col for col in df.columns
    if col not in technical_cols
    and col not in core_cols
    and col not in activity_attribute_cols
]

classified_cols = (
    technical_cols
    + core_cols
    + activity_attribute_cols
    + case_attribute_cols
)

other_cols = [
    col for col in df.columns
    if col not in classified_cols
]

print(f"Total columns in loaded file: {len(df.columns)}")
print(f"Technical index columns: {len(technical_cols)}")
print(f"Core event-log fields: {len(core_cols)}")
print(f"Activity attribute columns: {len(activity_attribute_cols)}")
print(f"Case attribute columns: {len(case_attribute_cols)}")
print(f"Other columns: {len(other_cols)}")

print()
print(f"Classified columns: {len(classified_cols)}")
print(f"Unclassified columns: {len(other_cols)}")

variable_groups = pd.DataFrame({
    "group": (
        ["technical_index"] * len(technical_cols)
        + ["core_event_log_field"] * len(core_cols)
        + ["activity_attribute"] * len(activity_attribute_cols)
        + ["case_attribute"] * len(case_attribute_cols)
        + ["other"] * len(other_cols)
    ),
    "column": (
        technical_cols
        + core_cols
        + activity_attribute_cols
        + case_attribute_cols
        + other_cols
    )
})

variable_groups

variable_groups["group"].value_counts().rename_axis("variable_group").reset_index(name="column_count")

"""## Case-level snapshot

The event log is organized at the event level, but many analyses begin by constructing a case-level table. Here we aggregate the event log to one row per case, using the first and last event dates, the number of recorded events, the number of distinct activity types, and selected case attributes.

Case attributes are static within a case and therefore can be carried forward using the first observed value for each case.
"""

# Make sure event dates are stored as datetime values.
df["date_filed"] = pd.to_datetime(df["date_filed"], errors="coerce")

# Select case attributes to carry into the case-level table.
# These are repeated across events belonging to the same case.
selected_case_attributes = [
    "city",
    "case_status",
    "case_type",
    "nature_suit",
    "is_mdl",
    "District_Judge",
    "Magistrate_Judge"
]

# Keep only selected attributes that exist in the dataset.
selected_case_attributes = [
    col for col in selected_case_attributes
    if col in df.columns
]

case_summary = (
    df.groupby("ucid")
      .agg(
          first_event_date=("date_filed", "min"),
          last_event_date=("date_filed", "max"),
          event_count=("Activity", "size"),
          unique_activity_count=("Activity", "nunique"),
          **{col: (col, "first") for col in selected_case_attributes}
      )
      .reset_index()
)

case_summary["case_los_days"] = (
    case_summary["last_event_date"] - case_summary["first_event_date"]
).dt.days

print(f"Cases in case-level table: {case_summary.shape[0]:,}")
print(f"Columns in case-level table: {case_summary.shape[1]:,}")

case_summary.head()

case_summary[
    [
        "event_count",
        "unique_activity_count",
        "case_los_days"
    ]
].describe()

"""## Case composition summaries

We next summarize selected case-level attributes. Because these attributes are repeated across all events belonging to the same case, we use the case-level table constructed above.

For `nature_suit`, we display the most common categories among civil cases. To match the descriptive table in the manuscript, the share is calculated out of all cases in the dataset.
"""

case_descriptor_cols = [
    "case_type",
    "case_status",
    "city",
    "is_mdl"
]

for col in case_descriptor_cols:
    summary = (
        case_summary[col]
        .value_counts(dropna=False)
        .rename_axis(col)
        .reset_index(name="case_count")
    )
    summary["share_percent"] = (
        100 * summary["case_count"] / len(case_summary)
    ).round(2)

    print(f"\n{col}")
    display(summary)


# Nature of suit is defined for civil cases.
# To match the manuscript's descriptive table, shares are calculated out of all cases.
civil_cases = case_summary.loc[case_summary["case_type"] == "cv"]

nature_suit_summary = (
    civil_cases["nature_suit"]
    .value_counts(dropna=False)
    .rename_axis("nature_suit")
    .reset_index(name="case_count")
)

nature_suit_summary["share_percent_all_cases"] = (
    100 * nature_suit_summary["case_count"] / len(case_summary)
).round(2)

print("\nTop nature_suit categories among civil cases")
display(nature_suit_summary.head(10))

"""## Activity summaries

We next summarize the standardized procedural activities recorded in the event log. Unlike the previous section, which used the case-level table, this section works directly with the event-level dataset because each row corresponds to one event.
"""

activity_summary = (
    df["Activity"]
    .value_counts(dropna=False)
    .rename_axis("Activity")
    .reset_index(name="event_count")
)

activity_summary["share_percent_events"] = (
    100 * activity_summary["event_count"] / len(df)
).round(2)

print(f"Number of distinct activities: {activity_summary.shape[0]:,}")
display(activity_summary)

"""## Activity attribute summaries

Activity attributes provide additional information about the procedural role or subtype of an event. In the dataset, these are stored as Boolean `attribute_*` columns.

The column `attribute_duplicates` is not summarized here because it is a count variable rather than a Boolean activity attribute.
"""

activity_attribute_cols = [
    col for col in df.columns
    if col.startswith("attribute_") and df[col].dtype == "bool"
]

print(f"Boolean activity attribute columns: {len(activity_attribute_cols):,}")

activity_attribute_summary = pd.DataFrame({
    "activity_attribute": activity_attribute_cols,
    "event_count": [df[col].sum() for col in activity_attribute_cols]
})

activity_attribute_summary["share_percent_events"] = (
    100 * activity_attribute_summary["event_count"] / len(df)
).round(2)

activity_attribute_summary = activity_attribute_summary.sort_values(
    "event_count", ascending=False
).reset_index(drop=True)

display(activity_attribute_summary.head(20))

"""## Length-of-stay summaries

Length of stay is calculated at the case level as the number of days between the first and last recorded event observed in the event log for each case.

We summarize length of stay for all cases and then separately for closed and open cases, following the descriptive logic used in the manuscript.
"""

# Overall length-of-stay summary
case_summary["case_los_days"].describe()

los_table = (
    case_summary
    .groupby("case_status")["case_los_days"]
    .agg(
        count="count",
        mean="mean",
        std="std",
        min="min",
        q25=lambda x: x.quantile(0.25),
        median="median",
        q75=lambda x: x.quantile(0.75),
        max="max"
    )
    .round(0)
    .astype(int)
    .reset_index()
)

los_table

"""## Basic plots

Finally, we create a few simple plots that help visualize the event log: the most frequent activities, the evolution of filed, terminated, and pending cases over time, and the distribution of length of stay for closed cases.

The filed/terminated/pending plot follows the descriptive logic used in the manuscript figure. The length-of-stay plot is shown for closed cases only and does not trim the right tail.
"""

top_activities = activity_summary.head(15).sort_values("event_count")

plt.figure(figsize=(8, 6))
plt.barh(top_activities["Activity"], top_activities["event_count"])
plt.xlabel("Number of events")
plt.ylabel("Activity")
plt.title("Top 15 activities in the NDIL event log")
plt.tight_layout()
plt.show()

# Cases filed, terminated, and pending over time
# This follows the logic used in the manuscript figure.
# A case is counted as pending in each month from its filing date
# through its terminating date.

df_filtered = case_summary.copy()

# Use the event-log-based case-level dates.
df_filtered["filing_date"] = pd.to_datetime(
    df_filtered["first_event_date"],
    errors="coerce"
)

df_filtered["terminating_date"] = pd.to_datetime(
    df_filtered["last_event_date"],
    errors="coerce"
)

# Keep cases with valid filing and terminating dates.
df_filtered = df_filtered.dropna(
    subset=["filing_date", "terminating_date"]
).copy()

# Step 1: Prepare the expanded dataset at a monthly level.
expanded_rows = []

for _, row in df_filtered.iterrows():
    start_month = row["filing_date"].to_period("M")
    end_month = row["terminating_date"].to_period("M")

    months = pd.period_range(
        start=start_month,
        end=end_month,
        freq="M"
    )

    for month in months:
        expanded_rows.append({
            "ucid": row["ucid"],
            "month": month
        })

expanded_df = pd.DataFrame(expanded_rows)

# Step 2: Group by month and count the number of pending cases.
monthly_open_cases = expanded_df.groupby("month").size()
monthly_open_cases.index = monthly_open_cases.index.to_timestamp()

# Step 3: Create the plot.
fig, ax1 = plt.subplots(figsize=(12, 6))

ax1.hist(
    df_filtered["terminating_date"],
    bins=100,
    alpha=0.5,
    label="Terminated Cases"
)

ax1.hist(
    df_filtered["filing_date"],
    bins=100,
    alpha=0.5,
    label="Filed Cases"
)

ax1.set_title("NDIL - Cases Filed, Terminated, and Pending Over Time")
ax1.set_xlabel("Year")
ax1.set_ylabel("Count (Filed/Terminated Cases)")
ax1.grid(True)

# Match the manuscript figure window.
ax1.set_xlim(
    pd.Timestamp("2004-01-01"),
    pd.Timestamp("2018-12-31")
)

# Step 4: Add pending cases line on a secondary y-axis.
ax2 = ax1.twinx()

ax2.plot(
    monthly_open_cases.index,
    monthly_open_cases.values,
    color="darkgrey",
    linewidth=2,
    label="Pending Cases"
)

ax2.set_ylabel("Count (Pending Cases)")

# Add legends for both axes.
fig.legend(
    loc="upper left",
    bbox_to_anchor=(0.15, 0.85),
    bbox_transform=fig.transFigure
)

plt.tight_layout()
plt.show()

# Distribution of length of stay for closed cases only
# Uses the case-level table constructed above.

df_los_closed = case_summary.loc[
    case_summary["case_status"] == "closed",
    ["case_los_days"]
].copy()

df_los_closed = df_los_closed.rename(columns={"case_los_days": "length_of_stay"})
df_los_closed = df_los_closed.dropna()
df_los_closed = df_los_closed.loc[df_los_closed["length_of_stay"] >= 0]

plt.figure(figsize=(12, 6))

sns.histplot(
    data=df_los_closed,
    x="length_of_stay",
    kde=True,
    stat="density"
)

plt.title("Distribution of Length of Stay, Closed Cases")
plt.xlabel("Length of Stay (Days)")
plt.ylabel("Density")
plt.xlim(left=0)

plt.tight_layout()
plt.show()

